    # Objetivo: verificar se um número inteiro está no intervalo fechado de 1 a 100.

    # inserrção de número

print("Insira um número inteiro aqui: ")
num = int(input())

    # verificação se o número está no intervalo de 1 a 100

if num >= 1 and num <= 100:
    print("Dentro do intervalo.")
else:
    print("Fora do intervalo.")