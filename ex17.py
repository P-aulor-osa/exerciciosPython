    # Objetivo: Ler um número inteiro, e informar se é positivo, negativo ou zero.

    # inserção de número

print("Insira um número aqui: ")
num = int(input())

    # verficação se o número é menor, maior ou igual a 0

if num > 0:
    print("Positivo.")
elif num < 0:
    print("Negativo.")
else:
    print("Zero.")