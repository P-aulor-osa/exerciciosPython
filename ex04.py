    # Objetivo: Converter valores térmicos em medida Celsius para Fahrenheit

    # inserção do valor a ser convertido
celsius = float(input("Insira o valor em Celsius: "))

    # operação de conversão
     
fahren = celsius * 1.8 + 32

    # resultado
print(f"O valor convertido em Fahrenheit é: {fahren:.1f}")
